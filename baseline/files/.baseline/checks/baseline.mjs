// Fails if a Baseline Block or Baseline File (CONTEXT.md) was edited by hand, or if the baseline
// plugin was switched off. The hash in each marker is of the content repo-setup wrote, so this
// needs nothing but the repository. To restore or update them: npx @janesenaj42/repo-setup
//
// repo-setup imports this file for the same marker format, so the format lives in one place.
// Usage: node .baseline/checks/baseline.mjs   Run by the pre-commit hook (.baseline/lefthook.yml).
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, readFileSync } from "node:fs";
import { basename, extname } from "node:path";
import { pathToFileURL } from "node:url";

export const HASH_LENGTH = 12;
export const PLUGIN = "baseline@repo-setup";
/** Files that hold Baseline Blocks, in any folder: the project's own lines go after the last block. */
export const BLOCK_FILES = [".gitignore", ".gitattributes", ".editorconfig", ".prettierignore"];
/** Where Baseline Files are written (prefixes of paths from the repository root). */
export const FILE_PLACES = [
  ".claude/rules/",
  ".claude/hooks/",
  ".baseline/",
  "docs/adr/template.md",
  "commitlint.config.mjs",
];

const BLOCK_START = /^# >>> baseline: (\S+) sha256:([0-9a-f]+)/;
const FILE_MARK = /baseline-file sha256:([0-9a-f]+)/;
const NOTE = "generated by repo-setup; don't edit";

export const isBlockFile = (path) => BLOCK_FILES.includes(basename(path));
export const normalize = (text) => text.replace(/\r\n/g, "\n");
export const hash = (text) =>
  createHash("sha256").update(normalize(text)).digest("hex").slice(0, HASH_LENGTH);

// ---- Baseline Blocks --------------------------------------------------------

/** One block: start marker with its content's hash, the content, end marker. */
export function renderBlock(name, body) {
  const content = normalize(body).replace(/\n*$/, "");
  return [
    `# >>> baseline: ${name} sha256:${hash(content)} (${NOTE}: add your own lines after the last block)`,
    content,
    `# <<< baseline: ${name}`,
  ].join("\n");
}

/** The file's blocks, and everything outside them (the project's own lines). */
export function parseBlocks(text) {
  const lines = normalize(text).split("\n");
  const blocks = [];
  const own = [];
  for (let i = 0; i < lines.length; i += 1) {
    const start = BLOCK_START.exec(lines[i]);
    if (!start) {
      own.push(lines[i]);
      continue;
    }
    const end = lines.indexOf(`# <<< baseline: ${start[1]}`, i + 1);
    const stop = end === -1 ? lines.length : end;
    const content = lines.slice(i + 1, stop).join("\n");
    blocks.push({ name: start[1], hash: start[2], content, closed: end !== -1 });
    i = stop;
  }
  return { blocks, own: own.join("\n").replace(/^\n+/, "") };
}

export function blockProblems(path, text) {
  return parseBlocks(text).blocks.flatMap((block) => {
    if (!block.closed) return [`${path}: block "${block.name}" has no end marker`];
    if (hash(block.content) !== block.hash) return [`${path}: block "${block.name}" was edited`];
    return [];
  });
}

// ---- Baseline Files ---------------------------------------------------------

/** The marker line for a file, in its own comment syntax. */
function markerLine(path, digest) {
  const mark = `baseline-file sha256:${digest} (${NOTE}: re-run repo-setup to update)`;
  const ext = extname(path);
  if (ext === ".md" || ext === ".xml") return `<!-- ${mark} -->`;
  if (ext === ".json") return `  "//": "${mark}",`;
  if ([".js", ".mjs", ".cjs", ".ts", ".kts"].includes(ext)) return `// ${mark}`;
  return `# ${mark}`;
}

/** Where the marker goes: after front matter, a shebang, an XML declaration or a JSON brace. */
function markerIndex(lines) {
  if (lines[0] === "---") return lines.indexOf("---", 1) + 1;
  if (/^(#!|<\?xml|\{$)/.test(lines[0] ?? "")) return 1;
  return 0;
}

/** The file as repo-setup writes it: its content with a marker holding the content's hash. */
export function markFile(path, content) {
  const lines = normalize(content).split("\n");
  lines.splice(markerIndex(lines), 0, markerLine(path, hash(content)));
  return lines.join("\n");
}

/** The file's content without its marker, and the hash the marker holds; null if unmarked. */
export function readMarkedFile(text) {
  const lines = normalize(text).split("\n");
  const index = lines.findIndex((line) => FILE_MARK.test(line));
  if (index === -1) return null;
  const digest = FILE_MARK.exec(lines[index])[1];
  lines.splice(index, 1);
  return { content: lines.join("\n"), digest };
}

export function fileProblems(path, text) {
  const marked = readMarkedFile(text);
  if (marked === null || hash(marked.content) === marked.digest) return [];
  return [`${path}: was edited`];
}

// ---- The check --------------------------------------------------------------

function pluginProblems() {
  const path = ".claude/settings.json";
  if (!existsSync(path)) return [];
  const settings = JSON.parse(readFileSync(path, "utf8"));
  return settings.enabledPlugins?.[PLUGIN] === true
    ? []
    : [`${path}: "enabledPlugins": { "${PLUGIN}": true } was removed`];
}

/** Problems in the repository at `cwd`. */
export function check() {
  const tracked = execFileSync("git", ["ls-files"], { encoding: "utf8" }).split("\n");
  const problems = tracked
    .filter((path) => isBlockFile(path) || FILE_PLACES.some((p) => path.startsWith(p)))
    .filter((path) => existsSync(path))
    .flatMap((path) => {
      const text = readFileSync(path, "utf8");
      return isBlockFile(path) ? blockProblems(path, text) : fileProblems(path, text);
    });
  return [...problems, ...pluginProblems()];
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const problems = check();
  if (problems.length) {
    console.error(`Files repo-setup owns were changed:
${problems.map((problem) => `  - ${problem}`).join("\n")}

Restore them with \`npx @janesenaj42/repo-setup\`. Put your own lines after the last block in
.gitignore, .gitattributes and .editorconfig, or your own file beside a baseline file.`);
    process.exit(1);
  }
}
